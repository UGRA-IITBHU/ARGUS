RCON = [0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1B,0x36]


def _bytes(x: int):
    return [(x >> (8 * (15 - i))) & 0xFF for i in range(16)]


def _pack(b):
    x = 0
    for v in b:
        x = (x << 8) | v
    return x


def sub_bytes(state):
    return [SBOX[x] for x in state]


def shift_rows(s):
    return [
        s[0], s[5], s[10], s[15],
        s[4], s[9], s[14], s[3],
        s[8], s[13], s[2], s[7],
        s[12], s[1], s[6], s[11],
    ]


def xtime(a):
    return ((a << 1) ^ 0x1B) & 0xFF if a & 0x80 else (a << 1) & 0xFF


def mix_columns(s):
    out = [0] * 16
    for c in range(4):
        i = 4 * c
        a0, a1, a2, a3 = s[i:i+4]
        out[i+0] = xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3
        out[i+1] = a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3
        out[i+2] = a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3)
        out[i+3] = (xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3)
    return out


def add_round_key(s, k):
    return [a ^ b for a, b in zip(s, k)]


def key_expansion(key: int):
    k = _bytes(key)
    words = [k[i:i+4] for i in range(0, 16, 4)]

    for r in range(1, 11):
        t = words[-1][1:] + words[-1][:1]
        t = [SBOX[x] for x in t]
        t[0] ^= RCON[r]

        w0 = [a ^ b for a, b in zip(words[-4], t)]
        w1 = [a ^ b for a, b in zip(words[-3], w0)]
        w2 = [a ^ b for a, b in zip(words[-2], w1)]
        w3 = [a ^ b for a, b in zip(words[-1], w2)]
        words.extend([w0, w1, w2, w3])

    return [_pack(sum(words[4*r:4*r+4], [])) for r in range(11)]


def aes128_encrypt(plaintext: int, key: int) -> int:
    if not (0 <= plaintext < (1 << 128)):
        raise ValueError("plaintext must be a 128-bit integer")
    if not (0 <= key < (1 << 128)):
        raise ValueError("key must be a 128-bit integer")

    round_keys = key_expansion(key)
    state = _bytes(plaintext)

    state = add_round_key(state, _bytes(round_keys[0]))

    for r in range(1, 11):
        state = sub_bytes(state)
        state = shift_rows(state)
        if r != 10:
            state = mix_columns(state)
        state = add_round_key(state, _bytes(round_keys[r]))

    return _pack(state)


def encrypt_hex(plaintext_hex: str, key_hex: str) -> str:
    plaintext = int(plaintext_hex, 16)
    key = int(key_hex, 16)
    return f"{aes128_encrypt(plaintext, key):032x}"


